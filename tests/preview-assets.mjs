import assert from 'node:assert/strict';
import {resolveProjectURL,imageURL,cssImages,loadPreviewAssets} from '../src/preview-assets.js';
let checks=0;const check=(actual,expected)=>{assert.deepEqual(actual,expected);checks++;};
const png='data:image/png;base64,iVBORw==',svg='data:image/svg+xml;base64,PHN2Zz4=';
const images=[{path:'bild.png',dataURL:png},{path:'images/logo.svg',dataURL:svg},{path:'Bilder/Übung 1.png',dataURL:png}];
check(imageURL('bild.png','index.html',images),png);
check(imageURL('../bild.png','seiten/drei.html',images),png);
check(imageURL('/bild.png?v=2','seiten/drei.php',images),png);
check(imageURL('images/logo.svg#symbol','index.html',images),svg+'#symbol');
check(imageURL('Bilder/%C3%9Cbung%201.png','index.html',images),png);
check(cssImages('background:url(../bild.png)','css/style.css',images),'background:url("'+png+'")');
check(cssImages("background:url('../images/logo.svg')",'css/style.css',images),'background:url("'+svg+'")');
check(cssImages('a{background:url(bild.png)}b{background:url(missing.png)}','index.html',images),'a{background:url("'+png+'")}b{background:url(missing.png)}');
check(imageURL('missing.png','index.html',images),'missing.png');
check(imageURL('https://foreign.example/bild.png','index.html',images),'https://foreign.example/bild.png');
check(resolveProjectURL('https://workspace.invalid.evil.example/bild.png','index.html'),null);
check(resolveProjectURL('%ZZ.png','index.html'),null);
check(imageURL('data:image/png;base64,AA==','index.html',images),'data:image/png;base64,AA==');
check(await loadPreviewAssets([]),[]);
await assert.rejects(()=>loadPreviewAssets([{id:'a'.repeat(32),path:'malicious.html',mime:'text/html'}]),/Ungültiges/);checks++;
console.log(`${checks} preview image resolution/security checks passed.`);
