import assert from 'node:assert/strict';
import {graphRelationCatalog,graphRelationUsage,completeGraphModel,addGraphRelation,editGraphRelation,removeGraphRelation,setGraphEdge,graphTypeAppearance,addGraphNodeType,editGraphNodeType,removeGraphNodeType,setGraphNode} from '../src/graph-model.js';

const legacy={types:[],relations:[],nodes:[{id:'a',type:'Person'},{id:'b',type:'Firma'},{id:'c',type:'Person'}],edges:[{id:'ab',from:'a',to:'b',label:'kennt',properties:{seit:2020}},{id:'ac',from:'a',to:'c',label:'kennt'},{id:'cb',from:'c',to:'b',label:'kennt'}]};
const original=structuredClone(legacy),catalog=graphRelationCatalog(legacy);
assert.deepEqual(catalog,[{name:'kennt',from:'Person',to:'Firma'},{name:'kennt',from:'Person',to:'Person'}]);
assert.equal(graphRelationUsage(legacy,catalog[0]),2);
const model=completeGraphModel(legacy);
assert.deepEqual(model.types,[{name:'Person',fields:[]},{name:'Firma',fields:[]}]);
assert.deepEqual(model.edges,legacy.edges);
assert.deepEqual(completeGraphModel({...legacy,types:[{name:'Person'}]}).types[0].fields,[],'Old imports may omit the field list');
model.types.push({name:'Unbenutzt',fields:[{name:'Titel',type:'text',required:false}]});
assert.deepEqual(completeGraphModel(model).types,model.types,'Deriving preserves unused schema and fields');
const extended=addGraphRelation(legacy,{name:'  arbeitet bei  ',from:'Person',to:'Firma'});
assert.equal(extended.relations.at(-1).name,'arbeitet bei');
assert.equal(extended.relations.length,3,'Adding the first explicit type retains all previous relationships');
assert.throws(()=>addGraphRelation(extended,{name:'kennt',from:'Person',to:'Firma'}),/bereits/);
assert.throws(()=>addGraphRelation(legacy,{name:'constructor',from:'Person',to:'Firma'}),/gültige/);
assert.throws(()=>addGraphRelation(legacy,{name:'x',from:'missing',to:'Firma'}),/vorhandene/);
const renamed=editGraphRelation(legacy,0,{name:'arbeitet mit',from:'Person',to:'Firma'});
assert.deepEqual(renamed.edges.map(e=>e.label),['arbeitet mit','kennt','arbeitet mit'],'Renaming changes only the intended endpoint types');
assert.deepEqual(renamed.edges[0].properties,{seit:2020});
assert.throws(()=>editGraphRelation(legacy,0,{name:'kennt',from:'Firma',to:'Person'}),/noch von Verbindungen/);
assert.throws(()=>editGraphRelation(legacy,0,{name:'kennt',from:'Person',to:'Person'}),/bereits/);
assert.throws(()=>removeGraphRelation(legacy,0),/noch verwendet/);
const unusedChanged=editGraphRelation(extended,2,{name:'beschäftigt',from:'Firma',to:'Person'});
assert.deepEqual(unusedChanged.relations.at(-1),{name:'beschäftigt',from:'Firma',to:'Person'});
assert.equal(removeGraphRelation(unusedChanged,2).relations.length,2);
const edge={id:'neu',from:'c',to:'b',label:'arbeitet bei',properties:{seit:2026}};
const connected=setGraphEdge(extended,edge);
assert.deepEqual(connected.edges.at(-1),edge);
assert.throws(()=>setGraphEdge(extended,{...edge,from:'b',to:'c'}),/passt nicht/);
assert.throws(()=>setGraphEdge(extended,{...edge,label:'unbekannt'}),/passt nicht/);
assert.throws(()=>setGraphEdge(extended,{...edge,to:'missing'}),/passt nicht/);
const edited=setGraphEdge(connected,{...edge,label:'kennt'});
assert.equal(edited.edges.length,4);assert.equal(edited.edges.at(-1).label,'kennt');
assert.deepEqual(legacy,original,'All edits are atomic candidates; failures never mutate the active graph');
const custom=addGraphNodeType(legacy,{name:'Ort',icon:'location_on',color:'#227C91'});
assert.deepEqual(custom.types.at(-1),{name:'Ort',fields:[],icon:'location_on',color:'#227c91'});
assert.throws(()=>addGraphNodeType(custom,{name:'Ort',icon:'category',color:'#000000'}),/bereits/);
assert.throws(()=>addGraphNodeType(legacy,{name:'X',icon:'url(evil)',color:'#ffffff'}),/Icon/);
assert.throws(()=>addGraphNodeType(legacy,{name:'X',icon:'person',color:'red;display:none'}),/Farbe/);
const populated=setGraphNode(custom,{id:'place',type:'Ort',label:'Berlin',properties:{}});
assert.equal(populated.nodes.length,4);assert.equal(populated.types.at(-1).icon,'location_on');
assert.throws(()=>removeGraphNodeType(populated,2),/noch/);
assert.throws(()=>removeGraphNodeType(legacy,0),/noch/);
assert.equal(removeGraphNodeType(custom,2).types.length,2);
const rich=structuredClone(custom);rich.types[0].fields=[{name:'Alter',type:'number',required:false}];
const retyped=editGraphNodeType(rich,0,{name:'Mensch',icon:'person',color:'#b50072'});
assert.equal(retyped.nodes[0].type,'Mensch');assert.equal(retyped.nodes[2].type,'Mensch');
assert(retyped.relations.every(r=>r.from==='Mensch'));
assert.deepEqual(retyped.types[0].fields,rich.types[0].fields);assert.deepEqual(retyped.edges,rich.edges);
assert.throws(()=>editGraphNodeType(rich,0,{name:'Firma',icon:'person',color:'#ffffff'}),/bereits/);
assert.equal(graphTypeAppearance({name:'Person'}).icon,'person');
assert.equal(graphTypeAppearance({name:'Unternehmen'}).icon,'apartment');
assert.equal(graphTypeAppearance({color:'#ffffff'}).ink,'#000000');
assert.equal(graphTypeAppearance({color:'#000000'}).ink,'#ffffff');
assert(/^#[0-9a-f]{6}$/i.test(graphTypeAppearance({color:'bad',icon:'<script>'}).color));
assert.deepEqual(legacy,original,'Node-type edits also leave the source graph unchanged');
console.log('Graph ontology verified: reusable node/edge types, icons/colors, endpoint rules, atomic edits, cascading renames and safe removal.');
